let marks:number = 30;

if (marks >= 90){
    console.log(`You have got ${marks}, hence your grade is "A".`);
}else if(marks >=75){
    console.log(`You have got ${marks}, hence your grade is "B".`);
}else if(marks>=50){
    console.log(`You have got ${marks}, hence your grade is "C".`);
}else{
    console.log(`You have got ${marks}, hence your grade is "D".`);
}